import assert from 'node:assert/strict';
import {salesReply} from '../../supabase/functions/public-chat/conversation.ts';
const config={mini_enabled:true,mini_city_rates:{'ঢাকা':{hourly_rate:2000,travel:500},'ময়মনসিংহ':{hourly_rate:1000,travel:200}},mini_city_deposits:{'ঢাকা':2000,'ময়মনসিংহ':1000},photo_edit_rate:20,prebook_amount:2000,half_due_days:60,fixed_discount_percent:10};
const chat={auto_reply_enabled:true,faqs:[{question:'ময়মনসিংহ মুসলিম বিয়ে · প্রাথমিক কোটেশন',answer:'Essential ৳6,999 · অফিসের চূড়ান্ত কোটেশন প্রয়োজন।'}]};
const reply=(m:string,h:string[]=[])=>salesReply(m,h,config,chat)!;
assert.doesNotMatch(reply('Hello').reply,/6999|6,999|23,998/);
assert.match(reply('মুসলিম বিয়ে').reply,/কোন শহরে/);
assert.match(reply('ময়মনসিংহ',['মুসলিম বিয়ে']).reply,/6,999/);
assert.match(reply('ঢাকা',['মুসলিম বিয়ে','ময়মনসিংহ']).reply,/ঢাকা/);
assert.match(reply('১ ঘণ্টার ক্যাজুয়াল ফটোশুট ময়মনসিংহ').reply,/1,200/);
assert.match(reply('২ ঘণ্টা ঢাকা').reply,/4,500/);
assert.match(reply('১ ঘণ্টা',['ঢাকা','ময়মনসিংহ','ক্যাজুয়াল শুট']).reply,/1,200/);
assert.match(reply('বাজেট কম').reply,/অনুমোদন|৫০%/);
assert.match(reply('অগ্রিম কত').reply,/৫০%/);
assert.equal(reply('বুকিং করব').links?.[0].href,'/booking');
assert.match(reply('ডিসকাউন্ট কত').reply,/10%/);
assert.match(reply('১৩ ঘণ্টা ঢাকা').reply,/১–১২/);
assert.doesNotMatch(salesReply('ময়মনসিংহ',['মুসলিম বিয়ে'],config,{...chat,auto_reply_enabled:false})!.reply,/6,999/);
console.log('13 sales conversation checks passed');
